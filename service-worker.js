function isSensitiveServicePath(pathname){
  // API and identity endpoints may return short-lived TURN credentials,
  // capabilities or player data. The Cache API ignores Cache-Control:no-store
  // on cache.put(), so these requests must never reach a caching branch.
  return /^\/(?:api|rest|auth|functions|storage)(?:\/|$)/.test(pathname);
}

async function precacheShell(){
  const cache=await caches.open(CACHE);
  const failed=[];
  // Precache only the PWA entrypoints. Loading every poster and script in
  // parallel during install can starve mobile room RPCs and stall the UI.
  // Other resources are cached when the player actually opens them.
  const critical=['/index.html','/en.html','/manifest.webmanifest'];
  for(const url of critical){
    try{
      const request=new Request(url,{cache:'reload'});
      const response=await fetch(request);
      if(!response.ok)throw new Error(`HTTP ${response.status}`);
      await cache.put(request,response);
    }catch(error){failed.push(`${url} (${String(error?.message||error)})`)}
  }
  if(failed.length)console.warn('[IGR SW] precache partial failure',failed);
}

self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    await precacheShell();
    await self.skipWaiting();
  })());
});

self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    const keys=await caches.keys();
    await Promise.all(keys.filter(k=>k.startsWith('igr-')&&k!==CACHE).map(k=>caches.delete(k)));
    // Upgrade from earlier releases: wipe any API credentials accidentally
    // stored in the retained cache, without discarding offline shell assets.
    const activeCache=await caches.open(CACHE);
    const cachedRequests=await activeCache.keys();
    await Promise.all(cachedRequests.filter(request=>{
      try{return isSensitiveServicePath(new URL(request.url).pathname)}catch{return false}
    }).map(request=>activeCache.delete(request)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch',event=>{
  const req=event.request;
  if(req.method!=='GET')return;
  const url=new URL(req.url);
  if(url.origin!==self.location.origin)return;
  // Prevent identity, WebRTC and future service endpoints from being cached,
  // served stale offline or exposed to Cache Storage scripts on this origin.
  if(isSensitiveServicePath(url.pathname))return;

  // Reuse immutable, versioned illustrations without hitting the network
  // each time a player revisits a scenario. Scripts stay network-first.
  if(url.pathname.startsWith('/assets/') && url.searchParams.has('v')){
    event.respondWith(caches.match(req).then(cached=>cached||fetch(req).then(response=>{
      if(response.ok){const copy=response.clone();event.waitUntil(caches.open(CACHE).then(c=>c.put(req,copy)).catch(()=>{}))}
      return response;
    })));
    return;
  }

  // Content-addressed v702 bundles cannot change at the same URL. Cache-first
  // makes repeat opens/offline resumes fast without caching any private RPC.
  if(/^\/igr-v702-(?:js|css)-[a-f0-9]{16}\.(?:js|css)$/.test(url.pathname)){
    event.respondWith(caches.match(req).then(cached=>cached||fetch(req).then(response=>{
      if(response.ok){
        const copy=response.clone();
        event.waitUntil(caches.open(CACHE).then(c=>c.put(req,copy)).catch(()=>{}));
      }
      return response;
    })));
    return;
  }

  const runtimeFile=req.mode==='navigate'||/\.(?:js|css|html)$/.test(url.pathname);
  const navigationKey=url.pathname==='/en.html'?'/en.html':'/index.html';
  const key=req.mode==='navigate'?navigationKey:req;

  if(runtimeFile){
    event.respondWith(fetch(req,{cache:'no-store'}).then(r=>{
      if(r.ok){
        const copy=r.clone();
        event.waitUntil(caches.open(CACHE).then(c=>c.put(key,copy)).catch(()=>{}));
      }
      return r;
    }).catch(()=>caches.match(key).then(cached=>cached||Response.error())));
    return;
  }

  event.respondWith(fetch(req,{cache:'no-store'}).then(r=>{
    if(r.ok){
      const copy=r.clone();
      event.waitUntil(caches.open(CACHE).then(c=>c.put(req,copy)).catch(()=>{}));
    }
    return r;
  }).catch(()=>caches.match(req).then(cached=>cached||Response.error())));
});
